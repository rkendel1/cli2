//! The optional zsh integration.
//!
//! Deliberately small: a completion function generated from the real clap
//! definition, and `c2`, a function that forwards its arguments verbatim to
//! the `cli2` executable. It defines no aliases, key bindings or shell
//! options, installs no `command_not_found_handler`, never evaluates text,
//! and never changes directory.

/// Bump when the generated integration changes shape.
pub const INTEGRATION_VERSION: u32 = 1;

/// Remove the parts of clap's script that would act on their own when
/// sourced: the `#compdef` header and the trailing registration, which calls
/// `compdef` unguarded. The integration registers completion itself, guarded.
fn completion_body(script: &str) -> String {
    let mut lines: Vec<&str> = script.lines().collect();
    if lines.first().is_some_and(|l| l.starts_with("#compdef")) {
        lines.remove(0);
    }
    if let Some(i) = lines.iter().rposition(|l| {
        l.trim_start()
            .starts_with("if [ \"$funcstack[1]\" = \"_cli2\" ]")
    }) {
        lines.truncate(i);
    }
    lines.join("\n").trim_end().to_string()
}

pub fn zsh_integration(completion_script: &str) -> String {
    let version = env!("CARGO_PKG_VERSION");
    let completion = completion_body(completion_script);
    format!(
        r#"# cli2 zsh integration, format version {INTEGRATION_VERSION} (generated by cli2 {version}).
#
# Optional. cli2 works without this file in any terminal. This adds:
#   - c2: a short name for `cli2`; every argument is forwarded unchanged.
#   - tab completion for cli2 and c2, generated from cli2's own commands.
#
# It does not replace zsh, and it does not touch your aliases, key bindings,
# shell options or working directory. Ordinary commands (git, cargo, npm, ...)
# are never routed through cli2. It is safe to source more than once.
#
# To disable: remove or comment out the line that sources this file in ~/.zshrc,
# then start a new shell. To regenerate after upgrading cli2:
#   cli2 shell-init zsh > "${{CLI2_HOME:-$HOME/.local/share/cli2}}/shell/cli2.zsh"

# c2 "find all references to authentication"
# c2 plan "run the project tests"
# c2 scan --rebuild
# Approval, verification, policy and evidence are handled by cli2 exactly as
# when it is run directly; c2 never adds flags such as --yes.
c2() {{
  emulate -L zsh
  if (( $# == 0 )); then
    print -u2 -r -- 'c2: usage: c2 "<what you want to do>" [cli2 options]   (see: cli2 --help)'
    return 2
  fi
  if (( ! $+commands[cli2] )); then
    print -u2 -r -- 'c2: the cli2 executable was not found on PATH.'
    print -u2 -r -- 'c2: install it with `cargo install --path crates/cli2` (from the cli2 repository) and make sure ~/.cargo/bin is on PATH.'
    return 127
  fi
  command cli2 "$@"
}}

# ---- completion (generated from cli2's command definitions) ----
{completion}

# Register once the completion system exists. If this file is sourced before
# compinit has run, registration happens once, just before the first prompt,
# and the one-shot hook then removes itself.
_cli2_register_completion() {{
  emulate -L zsh
  (( $+functions[compdef] )) || return 0
  compdef _cli2 cli2 c2
  if (( $+functions[add-zsh-hook] )); then
    add-zsh-hook -d precmd _cli2_register_completion
  fi
  unfunction _cli2_register_completion 2>/dev/null
  return 0
}}
if (( $+functions[compdef] )); then
  _cli2_register_completion
else
  autoload -Uz add-zsh-hook 2>/dev/null
  if (( $+functions[add-zsh-hook] )); then
    add-zsh-hook precmd _cli2_register_completion
  fi
fi
"#
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn strips_the_self_registering_parts() {
        let clap = "#compdef cli2\n\n_cli2() {\n  :\n}\n\nif [ \"$funcstack[1]\" = \"_cli2\" ]; then\n    _cli2 \"$@\"\nelse\n    compdef _cli2 cli2\nfi\n";
        let body = completion_body(clap);
        assert!(!body.contains("#compdef") && !body.contains("compdef _cli2 cli2"));
        assert!(body.contains("_cli2() {"));
    }
}
